import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';

const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8');
const tle = read('releases/v0.3.203/TLE.js');
const loader = read('loader/TLE-Remote-Loader-Stable-0.3.1.js');
const importTLE = JSON.parse(read('releases/v0.3.203/TLE-0.3.203-import.json'));
const importLoader = JSON.parse(read('loader/TLE-Remote-Loader-Stable-0.3.1.json'));
new vm.Script(tle);
new vm.Script(loader);
assert.equal(importTLE.type, 'script');
assert.equal(importLoader.type, 'script');
assert.equal(importTLE.content, tle);
assert.equal(importLoader.content, loader);
assert.match(tle, /version: '0\.3\.203'/);
assert.match(loader, /const LOADER_VERSION = '0\.3\.1'/);
assert.match(loader, /const CHANNEL = 'stable'/);
assert.match(loader, /main\/latest\.json/);
assert.match(loader, /const LOADER_KEY = '__TLE_REMOTE_LOADER_STABLE_V1__'/);
assert.match(loader, /await checkRemote\(\{ promptUpdate: false \}\);\s*\}\s*function destroy\(\)/);
assert.doesNotMatch(loader, /await checkRemote\(\{ promptUpdate: true \}\);\s*\}\s*function destroy\(\)/);
assert.match(loader, /async function adoptCurrent\(\)/);
assert.match(loader, /function getInfo\(\)/);
const infoBody = loader.split('  function getInfo() {')[1].split('  async function adoptCurrent()')[0];
assert.doesNotMatch(infoBody, /refreshButtons\(\)/, 'getInfo must not redispatch loader status events');
assert.match(loader, /'tle-loader-state-change'/);
assert.match(loader, /await verifySource\(record\)/);
assert.match(loader, /await readPreviousKnownGood\(\)/);
assert.match(loader, /SCRIPT_WIN\.confirm\(/);

assert.match(tle, /data-tle-runtime-version/);
assert.match(tle, /data-tle-action="install-update"/);
assert.match(tle, /data-tle-action="check-update"/);
assert.match(tle, /data-tle-action="adopt-loader"/);
assert.match(tle, /info\?\.updateAvailable && info\.availableVersion/);
assert.match(tle, /await loader\.loadRemote\(\)/);
assert.match(tle, /await loader\.checkRemote\(\)/);
assert.match(tle, /await loader\.adoptCurrent\(\)/);
assert.match(tle, /'tle-loader-state-change', syncRemoteUpdateUI, \{ signal: state\.abort\.signal \}/);
assert.match(tle, /tle-engine-update-dot/);
assert.match(tle, /button\.style\.setProperty\('top'/);
assert.match(tle, /button\.style\.setProperty\('right'/);
assert.match(tle, /button\.style\.setProperty\('bottom', 'auto', 'important'\)/);
assert.match(tle, /HOST_DOC\.documentElement\.appendChild\(button\)/);
assert.doesNotMatch(tle, /width: fit-content !important;/);
console.log('TLE Stable Loader UI regression passed (v0.3.203 / Stable Loader 0.3.1).');
